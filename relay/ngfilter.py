def _lattice(text, word):
    """text のどこかで、word を、かなはそのまま・漢字は読みのどれかで読んで、続けて読めるか。漢字を1つ以上使うときだけ。
    見つかれば (始め, 終わり)、なければ None。"""
    n, m = len(text), len(word)

    def walk(p, j, used):
        if j == m:
            return p if used else None
        if p >= n:
            return None
        c = text[p]
        if c == word[j]:
            e = walk(p + 1, j + 1, used)
            if e is not None:
                return e
        for r in _READ.get(c, ()):
            if word.startswith(r, j):
                e = walk(p + 1, j + len(r), True)
                if e is not None:
                    return e
        return None

    for i in range(n):
        c = text[i]
        if c != word[0] and not any(word.startswith(r) for r in _READ.get(c, ())):
            continue
        e = walk(i, 0, False)
        if e is not None:
            return i, e
    return None


