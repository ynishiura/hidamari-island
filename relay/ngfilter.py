def _loose(t, mask=False):
    if mask:
        t = ''.join('\x01' if c in _MASK else c for c in t)
    t = ''.join(c for c in t if c in _KEEP_SYM or c == '\x01' or unicodedata.category(c)[0] not in 'PS')
    t = re.sub('ー+', 'ー', _hira(t.translate(_LOOK)).translate(_SMALL))
    return re.sub('っ+', 'っ', t)                      # 小さい「っ」を重ねても同じ（くっっそ）


def _masked(text, words):
    """伏せ字の印が入った文に、言葉の一部を伏せた形があるか。隠していない文字が言葉の半分以上で、すべて一致するとき。"""
    if '\x01' not in text:
        return False
    edge = lambda j: j < 0 or j >= len(text) or text[j] in '、。!?\0'   # 文の始め・終わり・区切り
    for w in words:
        n, need = len(w), (len(w) + 1) // 2
        for i in range(len(text) - n + 1):
            seg = text[i:i + n]
            if '\x01' in seg and all(s == c or s == '\x01' for s, c in zip(seg, w)) and sum(s != '\x01' for s in seg) >= need:
                # 言葉の途中を伏せたもの（マ●コ・こ●す）は、どこにあっても止める。
                # 最初か最後の文字を伏せたもの（○んぽ・し●・ちん●）は、それだけで1つの言葉になっているときだけ
                # （ありがとう☆・おつかれ★ のような飾りの記号に当たらないように）
                if (seg[0] != '\x01' and seg[-1] != '\x01') or (edge(i - 1) and edge(i + n)):
                    return True
    return False


