def _hira(t):
    return ''.join(chr(ord(c) - 0x60) if 'ァ' <= c <= 'ヶ' else c for c in t)


def _kata(t):
    return ''.join(chr(ord(c) + 0x60) if 'ぁ' <= c <= 'ゖ' else c for c in t)


def _variants(words, readings=None, keep=()):
    """書いた形・読み（漢字の言葉）・ひらがな／カタカナに入れ替えた形を、そろえた形で返す。"""
    out = set()
    for w in words:
        forms = [w] + list((readings or {}).get(w, []))
        for f in forms:
            out.add(_norm(f))
            if f not in keep:
                out.add(_norm(_hira(f)))
                out.add(_norm(_kata(f)))
    return sorted(out, key=len, reverse=True)


